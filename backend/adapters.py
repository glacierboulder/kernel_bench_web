"""Trusted, backend-registered adapter types. Never accept shell commands from clients."""
from typing import Protocol

class Adapter(Protocol):
    def probe(self) -> dict: ...
    def start(self, task: dict, config: dict, workspace: str) -> str: ...
    def events(self, handle: str, after: int): ...
    def cancel(self, handle: str) -> None: ...
    def collect(self, handle: str) -> dict: ...

