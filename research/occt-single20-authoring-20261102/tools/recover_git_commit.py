"""Recover exact unsigned Git commit bytes from official API metadata.

GitHub API normalizes dates to UTC. Enumerate conventional timezone offsets,
but accept bytes only when Git's object SHA-1 equals the known official SHA.
This is content identity verification, not a guessed/recreated replacement SHA.
Tree objects are separately generated by git write-tree from the full archive.
"""
import argparse
from datetime import datetime
import hashlib
from itertools import product
import json
from pathlib import Path

def recover(d):
    if isinstance(d.get('content'),str):d=json.loads(d['content'])
    if d.get('verification',{}).get('signature'):raise ValueError('signed commit not supported by this tool')
    prefix=f"tree {d['tree']['sha']}\n"+''.join(f"parent {p['sha']}\n" for p in d['parents'])
    def line(role,offset):
        x=d[role];ts=int(datetime.fromisoformat(x['date'].replace('Z','+00:00')).timestamp())
        return f"{role} {x['name']} <{x['email']}> {ts} {offset}\n"
    offsets=[f'{sign}{h:02}{m:02}' for sign in ['+','-'] for h in range(15) for m in [0,15,30,45]]
    for ao,co in product(offsets,repeat=2):
        for message in [d['message'],d['message'].replace('\\n','\n')]:
            for ending in ['', '\n']:
                data=(prefix+line('author',ao)+line('committer',co)+'\n'+message+ending).encode()
                if hashlib.sha1(f'commit {len(data)}\0'.encode()+data).hexdigest()==d['sha']:return data
    raise ValueError('no exact SHA match; metadata is insufficient')
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('metadata',type=Path);p.add_argument('output',type=Path);a=p.parse_args()
    data=recover(json.loads(a.metadata.read_text()));a.output.write_bytes(data)
    print(hashlib.sha1(f'commit {len(data)}\0'.encode()+data).hexdigest())
